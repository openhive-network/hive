"""
Validating types of assets - only for validation models (generated by referring to `hiveio_api.fields.validation`).

The type decides the JSON form, msgspec validates it:

- `AssetHive`, `AssetHbd`, `AssetVests` (and the unions `AssetHiveOrHbd`, `AssetHiveOrVests`, `AnyAsset`) - NAI form
  (`{"amount": "1000", "precision": 3, "nai": "@@000000021"}`): structs with literals of NAIs and precisions of their
  kinds,
- `LegacyAssetHive`, `LegacyAssetHbd`, `LegacyAssetVests` (and the unions `LegacyAssetHiveOrHbd`,
  `LegacyAssetHiveOrVests`, `LegacyAnyAsset`) - legacy form (`"1.000 HIVE"`): strings matching a pattern of the amount
  with the precision of the kind and a symbol of the kind (of the mainnet or the testnet - `"1.000 TESTS"`).

Unions of the NAI form are base classes of their members (`AssetHive` is an `AssetHiveOrHbd`); they check the NAI and
the precision separately. Kinds are taken from `hiveio_api.fields.public` (the only definition of kinds of assets). The types only
validate - assets used as values are the user-friendly `Asset`.
"""

from __future__ import annotations

from typing import Annotated

import msgspec

from hiveio_api.fields.public import (
    HBD_ASSET,
    HBD_ASSET_NAI,
    HBD_ASSET_PRECISION,
    HIVE_ASSET,
    HIVE_ASSET_NAI,
    HIVE_ASSET_PRECISION,
    VESTS_ASSET,
    VESTS_ASSET_NAI,
    VESTS_ASSET_PRECISION,
    AssetInfo,
)

__all__ = [
    "AnyAsset",
    "AssetHbd",
    "AssetHive",
    "AssetHiveOrHbd",
    "AssetHiveOrVests",
    "AssetNaiAmount",
    "AssetVests",
    "LegacyAnyAsset",
    "LegacyAssetHbd",
    "LegacyAssetHive",
    "LegacyAssetHiveOrHbd",
    "LegacyAssetHiveOrVests",
    "LegacyAssetVests",
]

AssetNaiAmount = int | Annotated[str, msgspec.Meta(pattern=r"^-?\d+$")]
"""Amount of the NAI form in the smallest units - an integer, also as a string of digits (as sent by hived)."""


class AnyAsset(msgspec.Struct, frozen=True, forbid_unknown_fields=True):
    """
    HIVE, HBD or VESTS in the NAI form.

    Frozen (as its subclasses) - members narrow the types of fields of the unions, which type checkers allow only for
    fields which can not be changed.
    """

    amount: AssetNaiAmount
    precision: HIVE_ASSET_PRECISION | HBD_ASSET_PRECISION | VESTS_ASSET_PRECISION
    nai: HIVE_ASSET_NAI | HBD_ASSET_NAI | VESTS_ASSET_NAI


class AssetHiveOrHbd(AnyAsset, frozen=True):
    """HIVE or HBD in the NAI form."""

    precision: HIVE_ASSET_PRECISION | HBD_ASSET_PRECISION
    nai: HIVE_ASSET_NAI | HBD_ASSET_NAI


class AssetHiveOrVests(AnyAsset, frozen=True):
    """HIVE or VESTS in the NAI form."""

    precision: HIVE_ASSET_PRECISION | VESTS_ASSET_PRECISION
    nai: HIVE_ASSET_NAI | VESTS_ASSET_NAI


class AssetHive(AssetHiveOrHbd, AssetHiveOrVests, frozen=True):
    """HIVE in the NAI form."""

    precision: HIVE_ASSET_PRECISION
    nai: HIVE_ASSET_NAI


class AssetHbd(AssetHiveOrHbd, frozen=True):
    """HBD in the NAI form."""

    precision: HBD_ASSET_PRECISION
    nai: HBD_ASSET_NAI


class AssetVests(AssetHiveOrVests, frozen=True):
    """VESTS in the NAI form."""

    precision: VESTS_ASSET_PRECISION
    nai: VESTS_ASSET_NAI


def _legacy_form(*infos: AssetInfo) -> msgspec.Meta:
    """Pattern of the legacy form of the kinds - the amount with the precision of the kind and a symbol of the kind."""
    forms = (rf"-?\d+\.\d{{{info.precision}}} (?:{'|'.join(dict.fromkeys(info.symbol))})" for info in infos)
    return msgspec.Meta(pattern=f"^(?:{'|'.join(forms)})$")


LegacyAnyAsset = Annotated[str, _legacy_form(HIVE_ASSET, HBD_ASSET, VESTS_ASSET)]
LegacyAssetHiveOrHbd = Annotated[str, _legacy_form(HIVE_ASSET, HBD_ASSET)]
LegacyAssetHiveOrVests = Annotated[str, _legacy_form(HIVE_ASSET, VESTS_ASSET)]
LegacyAssetHive = Annotated[str, _legacy_form(HIVE_ASSET)]
LegacyAssetHbd = Annotated[str, _legacy_form(HBD_ASSET)]
LegacyAssetVests = Annotated[str, _legacy_form(VESTS_ASSET)]
