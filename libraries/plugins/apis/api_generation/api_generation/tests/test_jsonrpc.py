from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Literal

import pytest

from tests.generated_package import require_generated_package

require_generated_package()

from hiveio_api import UnsupportedTypeError  # noqa: E402
from hiveio_api._base import HiveModel, value_builder  # noqa: E402
from hiveio_api._communication.jsonrpc import JSONRPCError, JSONRPCRequest, JSONRPCResult, build_response  # noqa: E402

from schemas._preconfigured_base_model import PreconfiguredBaseModel  # noqa: E402
from schemas.fields.basic import AccountName  # noqa: E402
from schemas.fields.hive_int import HiveInt  # noqa: E402


@dataclass(frozen=True, kw_only=True)
class Account(HiveModel):
    name: str


@dataclass(frozen=True, kw_only=True)
class Witness(HiveModel):
    owner: str


class MsgspecAccount(PreconfiguredBaseModel):
    name: str


@dataclass(frozen=True, kw_only=True)
class TransferOperation(HiveModel):
    type: Literal["transfer_operation"]
    value: Account


@dataclass(frozen=True, kw_only=True)
class VoteOperation(HiveModel):
    type: Literal["vote_operation"]
    value: Witness


def response_with(result: object) -> dict[str, object]:
    return {"id": 3, "jsonrpc": "2.0", "result": result}


@pytest.mark.parametrize(
    ("expected_type", "result", "expected_result"),
    [
        (Account, {"name": "alice"}, Account(name="alice")),
        (list[Account], [{"name": "alice"}], [Account(name="alice")]),
        (Account | None, None, None),
        (Account | None, {"name": "alice"}, Account(name="alice")),
        (list[Account] | None, [{"name": "alice"}], [Account(name="alice")]),
        (dict[str, Account], {"x": {"name": "alice"}}, {"x": Account(name="alice")}),
        (list[list[int | Account]], [[1, {"name": "alice"}]], [[1, Account(name="alice")]]),
        (dict[str, Account] | str, {"x": {"name": "alice"}}, {"x": Account(name="alice")}),
        (str, "text", "text"),
        (list[list[str | None]], [["a", None]], [["a", None]]),
        (dict[str, int], {"x": 1}, {"x": 1}),
        (int | str, "1", "1"),
        (Literal["a", "b"], "a", "a"),
        (tuple[str, Account], ["x", {"name": "alice"}], ("x", Account(name="alice"))),
        (
            TransferOperation | VoteOperation,
            {"type": "vote_operation", "value": {"owner": "bob"}},
            VoteOperation(type="vote_operation", value=Witness(owner="bob")),
        ),
        (
            tuple[Literal["transfer"], Account] | tuple[Literal["vote"], Witness] | None,
            ["vote", {"owner": "bob"}],
            ("vote", Witness(owner="bob")),
        ),
        (tuple[Literal[0], Account] | tuple[Literal[1], Witness], [1, {"owner": "bob"}], (1, Witness(owner="bob"))),
    ],
)
def test_result_is_built_as_expected_type(expected_type: type[object], result: object, expected_result: object) -> None:
    # ACT
    response = build_response(expected_type, response_with(result))

    # ASSERT
    assert isinstance(response, JSONRPCResult)
    assert response.id_ == 3
    assert response.result == expected_result


def test_result_is_not_validated() -> None:
    # ARRANGE
    result = [{"name": 123, "unexpected": True}, "not an object", 5]

    # ACT
    response = build_response(list[Account], response_with(result))

    # ASSERT
    assert isinstance(response, JSONRPCResult)
    first, *rest = response.result
    assert first.name == 123
    assert first.unexpected is True  # type: ignore[attr-defined]
    assert rest == ["not an object", 5]


# `Any` as a value - annotation used by models generated by hiveio-api-client-generator
@pytest.mark.parametrize(
    "expected_type", [str, list[list[str]], dict[str, int | None], Any, object, list, Literal["a"]]
)
def test_results_without_public_models_are_not_traversed(expected_type: type[object]) -> None:
    # ARRANGE
    result = object()

    # ACT & ASSERT
    assert value_builder(expected_type)(result) is result


@pytest.mark.parametrize(
    "expected_type",
    [
        MsgspecAccount,
        list[MsgspecAccount],
        MsgspecAccount | None,
        HiveInt,
        AccountName,
        dict[str, HiveInt],
        Account | Witness | dict[str, Account],
        list[Account] | list[Witness],
        tuple[str, Account] | tuple[str, Witness],
    ],
)
def test_types_which_cannot_be_built_without_validation_are_rejected(expected_type: type[object]) -> None:
    # ACT & ASSERT
    with pytest.raises(UnsupportedTypeError):
        build_response(expected_type, response_with({}))


def test_response_without_result_is_error() -> None:
    # ARRANGE
    response = {"id": 1, "jsonrpc": "2.0", "error": {"code": -32000, "message": "boom"}}

    # ACT
    model = build_response(list[Account], response)

    # ASSERT
    assert isinstance(model, JSONRPCError)
    assert model.id_ == 1
    assert model.error["message"] == "boom"


def test_request_json() -> None:
    # ARRANGE
    request = JSONRPCRequest(method="database_api.find_accounts", params={"accounts": ["alice"]}, id_=7)

    # ACT & ASSERT
    assert request.json() == (
        '{"id": 7, "jsonrpc": "2.0", "method": "database_api.find_accounts", "params": {"accounts": ["alice"]}}'
    )
