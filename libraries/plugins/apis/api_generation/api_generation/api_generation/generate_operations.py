SCALARS: Final[dict[str, str]] = {"string": "str", "boolean": "bool", "integer": "int"}


def asset_info(symbol: str) -> AssetInfo:
    """Information about the kind of assets of a symbol of the description of operations - defined only by schemas."""
    info = asset_info_of_symbol(symbol)
    if info is None:
        raise ValueError(f"Unknown symbol of assets in the description of operations: {symbol}")
    return info


def asset_type(symbols: list[str], form: Form) -> str:
    """
    Name of the validating type of assets of the given symbols (`ASSET_TYPES`) in the given form.

    Args:
        symbols: Symbols of the kinds of assets the member takes (`x-hive-asset-symbols`).
        form: Form of the model - the type of the legacy form is `Legacy<type>` (e.g. `LegacyAssetHive`).
    """
    name = ASSET_TYPES[frozenset(asset_info(symbol) for symbol in symbols)]
    return name if form == "hf26" else f"Legacy{name}"


def field_name(key: str) -> str:
    """
    Name of the field of a member - `<key>_` when the key is a keyword or clashes with a method or a builtin.

    Args:
        key: Name of the member in JSON.
    """
    renamed = (
        keyword.iskeyword(key) or key in HIVE_MODEL_METHODS or key in OPERATION_METHODS or key in SHADOWING_MEMBERS
    )
    return f"{key}_" if renamed else key


@dataclass
class ModuleCode:
    """Code of a generated module - its imports, definitions and exported names."""

    imports: dict[str, set[str]] = field(default_factory=dict)
    definitions: list[str] = field(default_factory=list)
    exported: list[str] = field(default_factory=list)

    def import_name(self, module: str, name: str) -> str:
        """
        Import the name from the module into the generated module.

        Args:
            module: Module to import from (e.g. `typing`, or `.values` - another generated module of the package).
            name: The imported name.

        Returns:
            The name, to be used in the code of the module.
        """
        self.imports.setdefault(module, set()).add(name)
        return name

    def render(self, docstring: str) -> str:
        """
        Source code of the module - its docstring, imports, `__all__` and definitions.

        Args:
            docstring: Docstring of the module.
        """
        imports = "\n".join(
            f"from {module} import {', '.join(sorted(names))}" for module, names in self.imports.items()
        )
        exported = "".join(f'    "{name}",\n' for name in self.exported)
        definitions = "\n\n\n".join(self.definitions)
        return (
            f'"""{docstring}"""\n\nfrom __future__ import annotations\n\n{imports}\n\n'
            f"__all__ = [\n{exported}]\n\n\n{definitions}\n"
        )


class OperationsGenerator:
    """
    Generates the modules of operation models of one model variant from the description of operations.

    Public models are split into the modules `values`, `hf26` and `legacy` (see the module docstring), validation
    models are one module - its code is the target of all of them.
    """

    def __init__(self, description: Description, openapi_schemas: dict[str, Member], variant: ModelVariant) -> None:
        self.__description = description
        self.__openapi_schemas = openapi_schemas
        self.__variant = variant
        modules = (VALUES_MODULE, HF26_MODULE, LEGACY_MODULE) if variant.public else (OPERATIONS_MODULE,)
        self.__modules = {module: ModuleCode() for module in modules}
        self.__module_of: dict[str, str] = {}
        self.__current = [modules[0]]
        self.__defined: set[str] = set()
        self.__has_asset: dict[str, bool] = {}

    def generate(self) -> dict[str, str]:
        """Source code of the generated modules by their names."""
        hf26_members: list[str] = []
        legacy_members: list[str] = []
        hf26_values: list[str] = []
        legacy_values: list[str] = []
        hf26_operations: dict[str, str] = {}  # classes of values -> classes of operations of the HF26 form
        hf26_value_classes: dict[str, str] = {}  # names of operations -> classes of their values of the HF26 form
        legacy_value_classes: dict[str, str] = {}  # names of operations -> classes of their values of the legacy form
        for operation in self.__description["operations"]:
            name = operation["name"]
            value_class = f"{pascal_case(name)}Operation"
            with self.__in(VALUES_MODULE):
                hf26_value = self.__struct(value_class, operation["value"], "hf26", operation)
                hf26_values.append(hf26_value)
                hf26_value_classes[name] = hf26_value
            with self.__in(LEGACY_MODULE):
                legacy_value = self.__ref(
                    self.__struct(f"{value_class}Legacy", operation["value"], "legacy", operation)
                    if self.__node_has_asset(operation["value"])
                    else hf26_value
                )
                legacy_members.append(self.__legacy_wrapper(f"Legacy{value_class}", name, legacy_value))
                legacy_values.append(legacy_value)
                legacy_value_classes[name] = legacy_value
            with self.__in(HF26_MODULE):
                hf26_members.append(
                    self.__hf26_wrapper(f"Hf26{value_class}", f"{name}_operation", self.__ref(hf26_value))
                )
                hf26_operations[hf26_value] = hf26_members[-1]

        with self.__in(HF26_MODULE):
            self.__union(HF26_UNION, hf26_members, 'Any operation in HF26 form - `{"type": "<name>_operation", ...}`.')
            self.__transaction(HF26_TRANSACTION, HF26_UNION, "Transaction with operations in HF26 form.")
        with self.__in(VALUES_MODULE):
            self.__union(
                HF26_VALUE_UNION, hf26_values, f"Value of any operation in HF26 form (`value` of `{HF26_UNION}`)."
            )
        with self.__in(LEGACY_MODULE):
            self.__union(LEGACY_UNION, legacy_members, 'Any operation in legacy form - `["<name>", {...}]`.')
            self.__union(
                LEGACY_VALUE_UNION,
                legacy_values,
                f"Value of any operation in legacy form (second item of `{LEGACY_UNION}`).",
            )
            self.__transaction(
                LEGACY_TRANSACTION, LEGACY_UNION, "Transaction with operations in legacy form (e.g. of condenser_api)."
            )
        if self.__variant.public:
            with self.__in(VALUES_MODULE):
                for base_class in (OPERATION_BASE, VIRTUAL_OPERATION_BASE):
                    self.__reexport(base_class)
            with self.__in(HF26_MODULE):
                self.__hf26_conversion(hf26_operations, hf26_value_classes)
            with self.__in(LEGACY_MODULE):
                self.__legacy_conversion(legacy_value_classes)
        variant = "public" if self.__variant.public else "validation"
        return {
            module: code.render(
                f"Models of operations ({variant} variant{'' if module == OPERATIONS_MODULE else f', `{module}`'})"
                " - generated from the description of operations by api_generation/generate_operations.py, do not edit."
            )
            for module, code in self.__modules.items()
        }

    def exported(self) -> dict[str, str]:
        """Names defined by `generate` and modules defining them."""
        return dict(self.__module_of)

    # --- modules ---

    @property
    def __code(self) -> ModuleCode:
        return self.__modules[self.__current[-1]]

    @contextmanager
    def __in(self, module: str) -> Iterator[None]:
        """Define the code in the given module (the only module of validation models)."""
        self.__current.append(module if module in self.__modules else OPERATIONS_MODULE)
        try:
            yield
        finally:
            self.__current.pop()

    def __ref(self, name: str) -> str:
        """Name defined by the generator, imported into the current module when another module defines it."""
        module = self.__module_of.get(name)
        if module is not None and module != self.__current[-1]:
            self.__code.import_name(f".{module}", name)
        return name

    # --- forms ---

    def __hf26_wrapper(self, class_name: str, tag: str, value_class: str) -> str:
        if self.__variant.public:
            # a plain subclass of the generic envelope - only the envelope is a dataclass (cheap to define), the
            # annotations type the tag and tell the class of the value to build
            literal = self.__code.import_name("typing", "Literal")
            envelope = self.__envelope()
            self.__define(
                class_name,
                f"class {class_name}({envelope}[{value_class}]):\n"
                f'    """`{tag}` in HF26 form - `{{"type": "{tag}", "value": {{...}}}}`."""\n\n'
                f'    type: {literal}["{tag}"] = "{tag}"\n'
                f"    value: {value_class}",
            )
        else:
            # the tag is not a field of msgspec models - the class variable gives it as `type`, as of public models
            class_var = self.__code.import_name("typing", "ClassVar")
            literal = self.__code.import_name("typing", "Literal")
            self.__define(
                class_name,
                f'class {class_name}({self.__base_class()}, tag_field="type", tag="{tag}"):\n'
                f'    type: {class_var}[{literal}["{tag}"]] = "{tag}"\n'
                f"    value: {value_class}",
            )
        return class_name

    def __legacy_wrapper(self, class_name: str, tag: str | int, value_class: str) -> str:
        tag_code = json.dumps(tag)
        if self.__variant.public:
            literal = self.__code.import_name("typing", "Literal")
            type_alias = self.__code.import_name("typing", "TypeAlias")
            self.__define(class_name, f"{class_name}: {type_alias} = tuple[{literal}[{tag_code}], {value_class}]")
        else:
            self.__define(
                class_name,
                f"class {class_name}({self.__base_class()}, array_like=True, tag={tag_code}):\n    value: {value_class}",
            )
        return class_name

    def __hf26_conversion(self, operations: dict[str, str], value_classes: dict[str, str]) -> None:
        """`hf26_operation` - the operation of the HF26 form of a value (of any form), see `hf26_operation_of`."""
        final = self.__code.import_name("typing", "Final")
        cast = self.__code.import_name("typing", "cast")
        values = self.__ref(HF26_VALUE_UNION)
        operation_base = self.__operation_base()
        convert = self.__import_from_base_module(HF26_CONVERSION)
        mapping = "".join(f"    {self.__ref(value)}: {operation},\n" for value, operation in operations.items())
        self.__define(
            "_HF26_OPERATIONS",
            f"_HF26_OPERATIONS: {final}[dict[type[{values}], type[{HF26_UNION}]]] = {{\n{mapping}}}\n"
            '"""Operations of the HF26 form by the classes of their values."""',
            exported=False,
        )
        self.__define(
            "_HF26_VALUES",
            f"_HF26_VALUES: {final}[dict[str, type[{values}]]] = {self.__classes_by_names(value_classes)}\n"
            '"""Classes of values of operations of the HF26 form by names of the operations."""',
            exported=False,
        )
        self.__define(
            "hf26_operation",
            f"def hf26_operation(value: {operation_base}) -> {HF26_UNION}:\n"
            '    """\n'
            "    The operation of the HF26 form with the given value - e.g. `Hf26TransferOperation(value=transfer)`.\n"
            "\n"
            "    A value of the legacy form of an operation with assets becomes the value of the HF26 form (the assets keep\n"
            "    their amounts - they take the NAI form of the fields when serialized).\n"
            '    """\n'
            f'    return {cast}("{HF26_UNION}", {convert}(value, _HF26_OPERATIONS, _HF26_VALUES))',
        )

    def __legacy_conversion(self, value_classes: dict[str, str]) -> None:
        """`legacy_operation` - the operation of the legacy form of a value (of any form), see `legacy_operation_of`."""
        final = self.__code.import_name("typing", "Final")
        cast = self.__code.import_name("typing", "cast")
        operation_base = self.__operation_base()
        convert = self.__import_from_base_module(LEGACY_CONVERSION)
        self.__define(
            "_LEGACY_VALUES",
            f"_LEGACY_VALUES: {final}[dict[str, type[{LEGACY_VALUE_UNION}]]] = "
            f"{self.__classes_by_names(value_classes)}\n"
            '"""Classes of values of operations of the legacy form by names of the operations."""',
            exported=False,
        )
        self.__define(
            "legacy_operation",
            f"def legacy_operation(value: {operation_base}) -> {LEGACY_UNION}:\n"
            '    """\n'
            "    The operation of the legacy form with the given value - e.g. `(\"transfer\", transfer)`.\n"
            "\n"
            "    A value of the HF26 form of an operation with assets becomes the value of the legacy form (the assets keep\n"
            "    their amounts - they take the legacy form of the fields when serialized).\n"
            '    """\n'
            f'    return {cast}("{LEGACY_UNION}", {convert}(value, _LEGACY_VALUES))',
        )

    def __classes_by_names(self, classes: dict[str, str]) -> str:
        """A dict of the classes (imported when defined by another module) by names of operations."""
        return "{\n" + "".join(f'    "{name}": {self.__ref(class_)},\n' for name, class_ in classes.items()) + "}"

    def __union(self, name: str, members: list[str], docstring: str) -> None:
        type_alias = self.__code.import_name("typing", "TypeAlias")
        union = "\n    | ".join(members)
        self.__define(name, f'{name}: {type_alias} = (\n    {union}\n)\n"""{docstring}"""')

    def __envelope(self) -> str:
        """The base of public models of the HF26 form of variants, exported by the module of values."""
        with self.__in(VALUES_MODULE):
            if HF26_ENVELOPE not in self.__defined:
                self.__defined.add(HF26_ENVELOPE)
                self.__import_from_base_module(HF26_ENVELOPE)
                self.__reexport(HF26_ENVELOPE)
        return self.__ref(HF26_ENVELOPE)

    # --- transactions ---

    def __transaction(self, class_name: str, union: str, docstring: str) -> None:
        lines = [
            self.__public_class(class_name)
            if self.__variant.public
            else f"class {class_name}({self.__base_class()}, kw_only=True):\n",
            f'    """{docstring}"""\n\n',
        ]
        template = self.__openapi_schemas[TRANSACTION_TEMPLATE]
        assert set(template.get("required", [])) == set(template["properties"]), "All members are required"
        lines.extend(
            f"    {field_name(key)}: {self.__openapi_annotation(member)}\n"
            for key, member in template["properties"].items()
        )
        lines.append(f"    operations: list[{union}]")
        self.__define(class_name, "".join(lines))

    def __openapi_annotation(self, member: Member) -> str:
        """Annotation of a member described in openapi.json - Hive types and builtin scalars, otherwise `object`."""
        if "$ref" in member:
            return self.__openapi_annotation(self.__openapi_schemas[member["$ref"].split("/")[-1]])
        if "x-hive-type" in member:
            return self.__hive_type(member["x-hive-type"])
        if member.get("format") == "date-time":
            return self.__hive_type("HiveDateTime")
        if member.get("type") == "array":
            return f"list[{self.__openapi_annotation(member.get('items', {}))}]"
        if member.get("type") in SCALARS:
            return SCALARS[member["type"]]
        return "object"

    # --- structs ---

    def __struct(
        self, class_name: str, schema: Member, form: Form, operation: Operation | None, type_name: str | None = None
    ) -> str:
        """The model of the operation, or of the type `type_name` of the description used by operations."""
        if class_name in self.__defined:
            return class_name

        lines = [
            self.__public_class(class_name, operation)
            if self.__variant.public
            else f"class {class_name}({self.__base_class()}, kw_only=True):\n"
        ]
        if operation is not None:
            class_var = self.__code.import_name("typing", "ClassVar")
            lines.extend([
                f'    """Operation `{operation["name"]}` ({form} form)."""\n\n',
                f"    operation_id: {class_var}[int] = {operation['id']}\n",
                f"    virtual: {class_var}[bool] = {operation['virtual']}\n",
            ])
        elif type_name is not None:
            lines.append(f'    """Type `{type_name}` of values of operations ({form} form)."""\n\n')

        required = set(schema.get("required", []))
        for key, member in schema["properties"].items():
            annotation = self.__annotation(member, form)
            if key not in required:
                annotation = f"{annotation} | None"
            name = field_name(key)
            default = self.__default(member, form, key in required)
            if name != key or default is not None:
                lines.append(f"    {name}: {annotation} = {self.__field(key, name, default)}\n")
            else:
                lines.append(f"    {name}: {annotation}\n")
        if operation is not None:
            lines.append(self.__names(operation["name"]))
        if len(lines) == 1:
            lines.append("    pass\n")
        self.__define(class_name, "".join(lines).rstrip("\n"))
        return class_name

    @staticmethod
    def __names(name: str) -> str:
        """Methods giving the names of an operation in the notation of hived (as in its HF26 and legacy forms)."""
        return (
            "\n    @classmethod\n"
            "    def get_name(cls) -> str:\n"
            '        """Name of the operation, as in the legacy form."""\n'
            f'        return "{name}"\n'
            "\n    @classmethod\n"
            "    def get_name_with_suffix(cls) -> str:\n"
            '        """Name of the operation with the `_operation` suffix, as in the HF26 form."""\n'
            f'        return "{name}_operation"\n'
        )

    def __type(self, type_name: str, form: Form) -> str:
        schema = self.__description["types"][type_name]
        class_name = pascal_case(type_name)
        module = VALUES_MODULE
        if form == "legacy" and self.__type_has_asset(type_name):
            class_name += "Legacy"
            module = LEGACY_MODULE
        with self.__in(module):
            self.__struct(class_name, schema, form, None, type_name)
        return self.__ref(class_name)

    def __field(self, key: str, name: str, default: str | None) -> str:
        if self.__variant.public:
            field_ = self.__code.import_name("dataclasses", "field")
            arguments = [f'metadata={{"{ALIAS_METADATA_KEY}": "{key}"}}'] if name != key else []
        else:
            field_ = self.__code.import_name("msgspec", "field")
            arguments = [f'name="{key}"'] if name != key else []
        if default is not None:
            arguments.append(default)
        return f"{field_}({', '.join(arguments)})"

    # --- members ---

    def __annotation(self, member: Member, form: Form) -> str:
        if member.get("x-hive-type") == "asset":
            return self.__hive_type(asset_type(member["x-hive-asset-symbols"], form))
        if "x-hive-variant" in member:
            return self.__variant_union(member["x-hive-variant"], form)
        if "$ref" in member:
            return self.__type(member["$ref"].split("/")[-1], form)
        if "x-hive-type" in member:
            return self.__hive_type(member["x-hive-type"])
        if member.get("format") == "date-time":
            return self.__hive_type("HiveDateTime")
        json_type = member.get("type")
        if json_type == "array":
            items = member.get("items", {})
            if "prefixItems" in items:
                return f"list[tuple[{', '.join(self.__annotation(item, form) for item in items['prefixItems'])}]]"
            if "x-hive-variant" in items and not any(items["x-hive-variant"]):
                return self.__empty_list()
            return f"list[{self.__annotation(items, form)}]"
        return SCALARS[str(json_type)]

    def __hive_type(self, name: str) -> str:
        """The field type of the name - of the module of the variant (`schemas.fields.public` / `.validation`)."""
        return self.__code.import_name((public if self.__variant.public else validation).__name__, name)

    def __empty_list(self) -> str:
        """Variant only with placeholders for future types - never present, the list is always empty."""
        if self.__variant.public:
            return "list[object]"
        annotated = self.__code.import_name("typing", "Annotated")
        meta = self.__code.import_name("msgspec", "Meta")
        return f"{annotated}[list[object], {meta}(max_length=0)]"

    def __variant_union(self, alternatives: list[Reference | None], form: Form) -> str:
        members = []
        for index, alternative in enumerate(alternatives):
            if alternative is None:
                continue
            type_name = alternative["$ref"].split("/")[-1]
            value_class = self.__type(type_name, form)
            if form == "hf26":
                members.append(self.__hf26_wrapper(f"Hf26{pascal_case(type_name)}", type_name, value_class))
            else:
                members.append(self.__legacy_wrapper(f"Legacy{pascal_case(type_name)}", index, value_class))
        return " | ".join(members)

    def __default(self, member: Member, form: Form, required: bool) -> str | None:
        if not required:
            return "default=None"
        if "default" not in member:
            # lists of variants (extensions) are empty when not given - as in hived (a missing member keeps its default)
            return "default_factory=list" if "x-hive-variant" in member.get("items", {}) else None
        value = member["default"]
        if member.get("x-hive-type") == "asset":
            assert isinstance(value, dict), "Defaults of assets are objects"
            return self.__asset_default(value, form)
        if member.get("format") == "date-time":
            if self.__variant.public:  # dates of public models are immutable `HiveDateTime` values
                date = self.__code.import_name(public.__name__, "HiveDateTime")
                return f"default={date}({json.dumps(value)})"
            return f"default_factory=lambda: {self.__hive_type('HiveDateTime')}({json.dumps(value)})"
        return f"default={value!r}"

    def __asset_default(self, value: AssetDefault, form: Form) -> str:
        """
        The default is an asset of its symbol - the declared type may be a union of assets.

        Assets of public models take the form of their fields when serialized - the default is the same in both forms.
        Validation models take the asset in the form of the field - the struct of the NAI form or the legacy string.
        """
        asset = self.__code.import_name(public.__name__, "Asset")
        kind = Asset.kind_of(asset_info(value["symbol"]))
        default = f"{asset}.{kind.name}.satoshi({value['amount']})"
        if self.__variant.public:
            return f"default={default}"
        if form == "legacy":
            return f"default_factory=lambda: {default}.as_legacy()"
        convert = self.__code.import_name("msgspec", "convert")
        asset_form = self.__hive_type(asset_type([value["symbol"]], form))
        return f"default_factory=lambda: {convert}({default}.as_nai(), {asset_form})"

    # --- helpers ---

    def __public_class(self, class_name: str, operation: Operation | None = None) -> str:
        """Header of a public model - values of operations derive `OperationBase` / `VirtualOperationBase`."""
        dataclass_ = self.__code.import_name("dataclasses", "dataclass")
        base_class = self.__base_class() if operation is None else self.__operation_base_class(operation)
        return f"@{dataclass_}(kw_only=True)\nclass {class_name}({base_class}):\n"

    def __base_class(self) -> str:
        """Base class of models of the variant (e.g. `HiveModel`)."""
        base_class = self.__variant.model_options.base_class
        assert base_class is not None, "Model variants have base classes"
        return self.__import_from_base_module(base_class.rpartition(".")[2])

    def __import_from_base_module(self, name: str) -> str:
        """A name defined next to the base class of models of the variant (e.g. `OperationBase` of public models)."""
        base_class = self.__variant.model_options.base_class
        assert base_class is not None, "Model variants have base classes"
        return self.__code.import_name(base_class.rpartition(".")[0], name)

    def __operation_base(self) -> str:
        """Base class of values of all operations (`OperationBase`)."""
        return self.__import_from_base_module(OPERATION_BASE)

    def __operation_base_class(self, operation: Operation) -> str:
        """Base class of values of the operation."""
        return self.__import_from_base_module(VIRTUAL_OPERATION_BASE if operation["virtual"] else OPERATION_BASE)

    def __reexport(self, name: str) -> None:
        """Export a name imported by the current module (base classes of values of operations)."""
        self.__module_of[name] = self.__current[-1]
        self.__code.exported.append(name)

    def __define(self, name: str, code: str, *, exported: bool = True) -> None:
        if name in self.__defined:
            return
        self.__defined.add(name)
        self.__code.definitions.append(code)
        if exported:
            self.__module_of[name] = self.__current[-1]
            self.__code.exported.append(name)

    def __type_has_asset(self, type_name: str) -> bool:
        if type_name not in self.__has_asset:
            self.__has_asset[type_name] = False  # guards against recursion
            self.__has_asset[type_name] = self.__node_has_asset(self.__description["types"][type_name])
        return self.__has_asset[type_name]

    def __node_has_asset(self, node: object) -> bool:
        if isinstance(node, list):
            return any(self.__node_has_asset(item) for item in node)
        if not isinstance(node, dict):
            return False
        if node.get("x-hive-type") == "asset":
            return True
        if "$ref" in node:
            return self.__type_has_asset(node["$ref"].split("/")[-1])
        return any(self.__node_has_asset(value) for value in node.values())


def generate_operations(description_file: Path, openapi_file: Path, base_directory: Path) -> list[Path]:
    """
    Generate modules of operation models of both model variants.

    Args:
        description_file: The description of operations generated by hived (operations_description.json).
        openapi_file: openapi.json - the source of the members of transactions (`transaction_template`).
        base_directory: The base directory containing the api_generation folder.

    Returns:
        Paths of the generated modules of both variants - `__init__.py` of the public package, then the module of
        validation models.
    """
    description: Description = json.loads(description_file.read_text())
    openapi_schemas: dict[str, Member] = json.loads(openapi_file.read_text())["components"]["schemas"]
    generated: list[Path] = []
    written: list[Path] = []
    for variant in (PUBLIC, VALIDATION):
        package_directory = variant.package_directory(base_directory)
        generator = OperationsGenerator(description, openapi_schemas, variant)
        modules = generator.generate()
        if variant.public:
            directory = package_directory / OPERATIONS_MODULE
            outputs = {directory / "__init__.py": _package_code(generator.exported())}
            outputs |= {directory / f"{module}.py": code for module, code in modules.items()}
        else:
            outputs = {package_directory / f"{OPERATIONS_MODULE}.py": modules[OPERATIONS_MODULE]}
        for path, code in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(code)
        generated.append(next(iter(outputs)))
        written.extend(outputs)
    tidy_with_ruff(*written)
    return generated


def _package_code(module_of: dict[str, str]) -> str:
    """The public package of operations - imports a module when one of its names is used for the first time."""
    names_of = {module: sorted(name for name, of in module_of.items() if of == module) for module in set(module_of.values())}
    type_checking = "".join(
        f"    from .{module} import (\n" + "".join(f"        {name},\n" for name in names) + "    )\n"
        for module, names in sorted(names_of.items())
    )
    exported = "".join(f'    "{name}",\n' for name in sorted(module_of))
    imports = "".join(
        "    *aggregate_same_import(\n"
        + "".join(f'        "{name}",\n' for name in names)
        + f'        module=f"{{__name__}}.{module}",\n'
        "    ),\n"
        for module, names in sorted(names_of.items())
    )
    return (
        '"""\n'
        "Models of operations (public variant) - generated from the description of operations by\n"
        "api_generation/generate_operations.py, do not edit.\n"
        "\n"
        f"Names are imported from their modules when used for the first time: `{VALUES_MODULE}` (values of operations and\n"
        f"their types), `{HF26_MODULE}` (operations and transactions of the HF26 form), `{LEGACY_MODULE}` (values with assets of\n"
        "the legacy form, operations and transactions of the legacy form).\n"
        '"""\n'
        "\n"
        "from __future__ import annotations\n"
        "\n"
        "from typing import TYPE_CHECKING\n"
        "\n"
        "from hiveio_api._utilities.smart_lazy_import import aggregate_same_import, lazy_module_factory\n"
        "\n"
        "if TYPE_CHECKING:\n"
        f"{type_checking}"
        "\n"
        f"__all__ = [\n{exported}]\n"
        "\n"
        f"__getattr__ = lazy_module_factory(\n    globals(),\n{imports})\n"
    )
