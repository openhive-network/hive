"""
Generation of operation models from the description of operations generated by hived.

The description (`operations_description.json`, see cmake/operations_description_generation.cmake in hive) holds the
structure of operations and of the types they use, without the JSON forms in which hived serializes them. The forms
are built here, for both model variants:

- HF26 - `{"type": "transfer_operation", "value": {...}}`, assets in NAI form,
- legacy - `["transfer", {...}]`, assets in legacy form (`"1.000 HIVE"`); a variant of types (e.g. extensions) is
  `[<index of the type>, {...}]` instead of `{"type": "<type>", "value": {...}}`.

Transactions of both forms (`Transaction`, `TransactionLegacy`) hold the members of `transaction_template` of
openapi.json and a list of operations of their form.

Public models (the package `hiveio_api.operations`) are dataclasses with builtin field types - the legacy form of an
operation is a tuple. They are split into modules imported only when used: `values` (values of operations shared by both
forms and the types they use), `hf26` (operations of the HF26 form - subclasses of one generic dataclass
`Hf26Envelope`, `Transaction`) and `legacy` (values with assets of the legacy form, `TransactionLegacy`); the
package itself imports a module when one of its names is used. Validation models (`hiveio_api._validation.operations`)
are msgspec models with Hive types, tagged by the type of the operation. API models refer to the unions `Hf26Operation` and `LegacyOperation` and to the
transactions with `x-hive-type` annotations of openapi.json.

Operations are identified by their names in the notation of hived - `type` of the HF26 form (`transfer_operation`,
also of validation models, where it is the tag), the first item of the legacy form (`transfer`). Values of operations
give both: `get_name()` (`transfer`) and `get_name_with_suffix()` (`transfer_operation`). Public values of operations
derive `OperationBase` (`VirtualOperationBase` for virtual operations) of `hiveio_api._base`, exported by the package,
and tell their number (`operation_id` - the position in `hive::protocol::operation`) and whether they are `virtual`.
"""

