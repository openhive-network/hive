#! /bin/bash

set -xeuo pipefail

SCRIPTPATH="$( cd -- "$(dirname "$0")" >/dev/null 2>&1 ; pwd -P )"
BASE_DIR="${SCRIPTPATH}"

API_GENERATION_PACKAGE_DIR="${BASE_DIR}/api_generation"

# Full list of APIs to generate
DEFAULT_API_LIST=(
  "account_by_key_api"
  "account_history_api"
  "app_status_api"
  "beekeeper_api"
  "block_api"
  "bridge"
  "condenser_api"
  "database_api"
  "debug_node_api"
  "follow_api"
  "jsonrpc"
  "hive"
  "market_history_api"
  "network_broadcast_api"
  "network_node_api"
  "rc_api"
  "reputation_api"
  "search_api"
  "tags_api"
  "transaction_status_api"
  "wallet_bridge_api"
)

# Usage: generate_api_packages.sh --operations-description=<path> [api ...]
#   --operations-description - description of operations generated by the build of hived
#                              (<build directory>/operations_description.json)
OPERATIONS_DESCRIPTION=""
API_LIST=()
for arg in "$@"; do
  case "${arg}" in
    --operations-description=*) OPERATIONS_DESCRIPTION="${arg#*=}" ;;
    *) API_LIST+=("${arg}") ;;
  esac
done

if [ -z "${OPERATIONS_DESCRIPTION}" ]; then
  echo "--operations-description=<path> is required (operations_description.json from the build of hived)" >&2
  exit 1
fi
OPERATIONS_DESCRIPTION="$(realpath "${OPERATIONS_DESCRIPTION}")"

if [ "${#API_LIST[@]}" -eq 0 ]; then
  API_LIST=("${DEFAULT_API_LIST[@]}")
fi

# generated modules are recreated - the stale ones must not be imported while generating (the generator imports
# generated descriptions, which loads the package __init__.py)
rm -f "${BASE_DIR}/python_api_package/hiveio_api/__init__.py"
rm -f "${BASE_DIR}/python_api_package/hiveio_api/common.py"
rm -f "${BASE_DIR}/python_api_package/hiveio_api/operations.py"
rm -rf "${BASE_DIR}/python_api_package/hiveio_api/_validation"

# Operations first - models of APIs refer to them (transactions take their members from openapi.json)
echo "Generating models of operations from ${OPERATIONS_DESCRIPTION}..."
poetry run -C "${API_GENERATION_PACKAGE_DIR}" python "${BASE_DIR}/api_generation/generate_operation_models.py" \
  "${OPERATIONS_DESCRIPTION}" "${BASE_DIR}/../documentation/openapi.json" "${BASE_DIR}"

# Generate each API subpackage
for d in "${API_LIST[@]}"; do
  echo "Processing API: $d"
  poetry run -C "${API_GENERATION_PACKAGE_DIR}" python "${BASE_DIR}/api_generation/generate_api_definitions.py" "$d" "${BASE_DIR}"
done

# Generate root package files (__init__.py, README.md) from templates
echo "Generating root package files for hiveio_api..."
poetry run -C "${API_GENERATION_PACKAGE_DIR}" python "${BASE_DIR}/api_generation/generate_root_package.py" "${BASE_DIR}" "${API_LIST[@]}"

echo "Successfully generated hiveio_api package with ${#API_LIST[@]} APIs"
